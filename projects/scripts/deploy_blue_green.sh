#!/usr/bin/env bash
# Blue-green deploys for the labyrinth.ts stack (API slots + Caddy switch).
#
#   ./scripts/deploy_blue_green.sh                build the idle color, verify it, switch traffic to it
#   ./scripts/deploy_blue_green.sh --preview      build/refresh the PR preview slot; traffic untouched
#   ./scripts/deploy_blue_green.sh --switch-only  flip traffic to the other color, no rebuild (rollback)
#   ./scripts/deploy_blue_green.sh --status       print the active color and each slot's health
#
# Switch and status modes always print exactly one `active: <color>` line; the
# deploy workflow parses it. Switching rewrites caddy/Caddyfile and hot-reloads
# Caddy: zero downtime, and if the new color stops answering, Caddy fails over
# to the old one by itself. The Telegram bot is a singleton, not slotted — it is
# rebuilt in place from the tree this script runs on. The very first switch also
# retires the pre-blue-green `backend` container to free :8080 for Caddy: the
# one and only deploy that interrupts the tunnel, for a second or two.
set -euo pipefail
SELF="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"
cd "$(dirname "$SELF")/.."

COMPOSE=(docker compose -f docker-compose.server.yml)
CADDYFILE=caddy/Caddyfile
HEALTH_PATH=/api/v1/health
TIMEOUT="${TIMEOUT:-240}"

log() { printf '>>> %s\n' "$*"; }

take_lock() {
  # One deploy at a time: a PR preview, a merge deploy, and a human can collide.
  command -v flock >/dev/null || { echo "flock not found — run this on the Linux server" >&2; exit 1; }
  exec 9>/tmp/mekongpulse-deploy.lock
  flock -w 300 9 || { echo "another deploy holds /tmp/mekongpulse-deploy.lock" >&2; exit 1; }
}

active_color() {
  local color
  color="$(sed -n 's/^# active: //p' "$CADDYFILE" | head -1)"
  [ -n "$color" ] || { echo "no '# active:' marker in $CADDYFILE" >&2; exit 1; }
  echo "$color"
}

other_color() {
  if [ "$(active_color)" = blue ]; then echo green; else echo blue; fi
}

port_of() {  # published loopback port of a slot; empty when it is not running
  "${COMPOSE[@]}" port "backend-$1" 8080 2>/dev/null | awk -F: 'NF { print $NF }'
}

is_healthy() {
  local port
  port="$(port_of "$1")"
  [ -n "$port" ] || return 1
  curl -fsS -m 3 "http://127.0.0.1:${port}${HEALTH_PATH}" >/dev/null 2>&1
}

wait_healthy() {  # $1 = slot; dumps the log tail when it never answers
  local slot="$1" deadline=$((SECONDS + TIMEOUT))
  while ((SECONDS < deadline)); do
    if is_healthy "$slot"; then
      log "backend-$slot is healthy"
      return 0
    fi
    sleep 3
  done
  log "backend-$slot did not answer ${HEALTH_PATH} within ${TIMEOUT}s:"
  "${COMPOSE[@]}" logs --tail 30 "backend-$slot" || true
  return 1
}

render_caddyfile() {  # $1 = color that should serve traffic
  local active="$1" standby
  if [ "$active" = blue ]; then standby=green; else standby=blue; fi
  # Written in place (not write-then-rename) so the inode mounted into the
  # container cannot be swapped out from under Caddy.
  cat > "$CADDYFILE" <<EOF
# GENERATED by scripts/deploy_blue_green.sh — do not edit by hand.
# active: ${active}
#
# Fronts both API colors; the Cloudflare tunnel targets http://localhost:8080.
# lb_policy first serves the active color (listed first) and fails over to the
# other one when the active color stops answering its health probe.
:8080 {
	reverse_proxy backend-${active}:8080 backend-${standby}:8080 {
		lb_policy first
		health_uri ${HEALTH_PATH}
		health_interval 5s
		health_timeout 3s
		lb_try_duration 5s
	}
}
EOF
}

ensure_db() {
  "${COMPOSE[@]}" up -d db
}

drop_legacy_backend() {
  # One-time migration: the pre-blue-green `backend` container owns :8080, which
  # Caddy needs. Called only once the new color is verified, so the old API —
  # and the tunnel — keep serving until the actual switch. No-op afterwards.
  docker rm -sf mekongpulse-server-backend-1 >/dev/null 2>&1 || true
}

switch_to() {  # $1 = color that should serve traffic
  local target="$1" current
  current="$(active_color)"
  if [ "$current" = "$target" ]; then
    log "backend-$target already serves traffic"
    echo "active: $target"
    return 0
  fi
  if ! is_healthy "$target"; then
    log "refusing to switch: backend-$target is not answering ${HEALTH_PATH}"
    return 1
  fi
  drop_legacy_backend
  log "switching traffic: backend-$current → backend-$target"
  render_caddyfile "$target"
  "${COMPOSE[@]}" up -d caddy
  # A container created by the line above needs a moment before its admin API
  # answers, so retry; a genuine config error still fails after the fifth try.
  local attempt=0
  until "${COMPOSE[@]}" exec -T caddy caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile; do
    attempt=$((attempt + 1))
    [ "$attempt" -lt 5 ] || { log "caddy reload failed ${attempt} times; the previous config keeps serving"; return 1; }
    sleep 2
  done
  log "live: backend-$target · rollback target: backend-$current (still warm)"
  echo "active: $target"
}

rebuild_bot() {
  # The bot polls Telegram (one process per token) and reads the database and
  # the public audio URL, so it is not slotted: rebuilt in place after the
  # switch, and only when it is already running.
  if [ -n "$("${COMPOSE[@]}" --profile bot ps -q bot)" ]; then
    log "rebuilding the bot in place"
    "${COMPOSE[@]}" --profile bot up -d --build --no-deps bot
  fi
}

slot_line() {  # $1 = slot, $2 = suffix
  local port state
  port="$(port_of "$1")"
  if [ -z "$port" ]; then
    state="not running"
  elif is_healthy "$1"; then
    state="healthy"
  else
    state="unhealthy"
  fi
  printf '%-8s %-16s %s%s\n' "$1" "${port:+127.0.0.1:$port}" "$state" "${2:-}"
}

case "${1:-}" in
  "")
    take_lock
    ensure_db
    target="$(other_color)"
    log "building the idle color: backend-$target"
    "${COMPOSE[@]}" up -d --build --no-deps "backend-$target"
    wait_healthy "$target"
    switch_to "$target"
    rebuild_bot
    ;;
  --preview)
    take_lock
    ensure_db
    log "building the preview slot: backend-preview"
    "${COMPOSE[@]}" up -d --build --no-deps backend-preview
    wait_healthy preview
    log "preview API on 127.0.0.1:$(port_of preview) — not in the Caddy pool"
    ;;
  --switch-only)
    take_lock
    switch_to "$(other_color)"
    ;;
  --status)
    active="$(active_color)"
    echo "active: $active"
    for slot in blue green preview; do
      if [ "$slot" = "$active" ]; then slot_line "$slot" " · live"; else slot_line "$slot"; fi
    done
    ;;
  -h | --help)
    sed -n '2,15p' "$SELF" | sed 's/^# \{0,1\}//'
    ;;
  *)
    echo "unknown flag: $1 (try --help)" >&2
    exit 2
    ;;
esac
